-- GeoPulse: Snowflake GEOGRAPHY columns and CSV loading
-- Prepared script only: it has NOT been executed in your Snowflake account.
-- Upload these files to @GEOPULSE_DB.RAW.GEOPULSE_STAGE first:
-- GeoPulse_Hyderabad_Coffee_Shop_Locations.csv
-- GeoPulse_Hyderabad_Synthetic_GPS_Pings.csv
--
-- Source CSV column order:
-- Coffee shops: CoffeeShopID,CoffeeShopName,Area,Latitude,Longitude,LocationType
-- GPS: DeviceID,Latitude,Longitude,Timestamp

CREATE DATABASE IF NOT EXISTS GEOPULSE_DB;
CREATE SCHEMA IF NOT EXISTS GEOPULSE_DB.RAW;
USE DATABASE GEOPULSE_DB;
USE SCHEMA RAW;

CREATE OR REPLACE FILE FORMAT GEOPULSE_CSV_FORMAT
  TYPE = CSV SKIP_HEADER = 1
  FIELD_OPTIONALLY_ENCLOSED_BY = '"'
  EMPTY_FIELD_AS_NULL = TRUE TRIM_SPACE = TRUE
  ERROR_ON_COLUMN_COUNT_MISMATCH = TRUE;

CREATE STAGE IF NOT EXISTS GEOPULSE_STAGE
  FILE_FORMAT = GEOPULSE_CSV_FORMAT;

-- GEOGRAPHY stores spatial point objects derived from longitude/latitude.
CREATE TABLE IF NOT EXISTS RAW_GPS_PINGS (
  DEVICE_ID VARCHAR,
  LATITUDE FLOAT,
  LONGITUDE FLOAT,
  EVENT_TS TIMESTAMP_NTZ,
  SOURCE_FILE VARCHAR,
  LOADED_AT TIMESTAMP_NTZ DEFAULT CURRENT_TIMESTAMP(),
  LOCATION_GEOG GEOGRAPHY
);

CREATE TABLE IF NOT EXISTS RAW_COFFEE_SHOP_LOCATIONS (
  COFFEE_SHOP_ID VARCHAR,
  COFFEE_SHOP_NAME VARCHAR,
  AREA VARCHAR,
  LATITUDE FLOAT,
  LONGITUDE FLOAT,
  LOCATION_TYPE VARCHAR,
  SOURCE_FILE VARCHAR,
  LOADED_AT TIMESTAMP_NTZ DEFAULT CURRENT_TIMESTAMP(),
  LOCATION_GEOG GEOGRAPHY
);

-- Upload both CSVs to the stage in Snowsight, then inspect:
LIST @GEOPULSE_STAGE;

-- Load coffee shop CSV.
COPY INTO RAW_COFFEE_SHOP_LOCATIONS
  (COFFEE_SHOP_ID, COFFEE_SHOP_NAME, AREA, LATITUDE, LONGITUDE,
   LOCATION_TYPE, SOURCE_FILE)
FROM (
  SELECT $1::VARCHAR, $2::VARCHAR, $3::VARCHAR,
         TRY_TO_DOUBLE($4), TRY_TO_DOUBLE($5), $6::VARCHAR,
         METADATA$FILENAME
  FROM @GEOPULSE_STAGE
)
FILES = ('GeoPulse_Hyderabad_Coffee_Shop_Locations.csv')
FILE_FORMAT = (FORMAT_NAME = GEOPULSE_CSV_FORMAT)
ON_ERROR = 'ABORT_STATEMENT';

-- Load GPS ping CSV. Source timestamps have no timezone encoded.
COPY INTO RAW_GPS_PINGS
  (DEVICE_ID, LATITUDE, LONGITUDE, EVENT_TS, SOURCE_FILE)
FROM (
  SELECT $1::VARCHAR, TRY_TO_DOUBLE($2), TRY_TO_DOUBLE($3),
         TRY_TO_TIMESTAMP_NTZ($4, 'YYYY-MM-DD HH24:MI:SS'),
         METADATA$FILENAME
  FROM @GEOPULSE_STAGE
)
FILES = ('GeoPulse_Hyderabad_Synthetic_GPS_Pings.csv')
FILE_FORMAT = (FORMAT_NAME = GEOPULSE_CSV_FORMAT)
ON_ERROR = 'ABORT_STATEMENT';

-- Snowflake ST_MAKEPOINT expects longitude first, latitude second.
UPDATE RAW_GPS_PINGS
SET LOCATION_GEOG = ST_MAKEPOINT(LONGITUDE, LATITUDE)
WHERE LOCATION_GEOG IS NULL
  AND LATITUDE BETWEEN -90 AND 90
  AND LONGITUDE BETWEEN -180 AND 180;

UPDATE RAW_COFFEE_SHOP_LOCATIONS
SET LOCATION_GEOG = ST_MAKEPOINT(LONGITUDE, LATITUDE)
WHERE LOCATION_GEOG IS NULL
  AND LATITUDE BETWEEN -90 AND 90
  AND LONGITUDE BETWEEN -180 AND 180;

-- Validation: row counts, unique devices, geography population, timestamp range.
SELECT COUNT(*) AS GPS_ROWS,
       COUNT(DISTINCT DEVICE_ID) AS UNIQUE_DEVICES,
       COUNT_IF(LOCATION_GEOG IS NULL) AS GPS_ROWS_WITHOUT_GEOGRAPHY,
       MIN(EVENT_TS) AS FIRST_EVENT_TS, MAX(EVENT_TS) AS LAST_EVENT_TS
FROM RAW_GPS_PINGS;

SELECT COUNT(*) AS STORE_ROWS,
       COUNT_IF(LOCATION_GEOG IS NULL) AS STORES_WITHOUT_GEOGRAPHY,
       COUNT_IF(UPPER(LOCATION_TYPE) = 'EXISTING') AS EXISTING_STORES,
       COUNT_IF(UPPER(LOCATION_TYPE) = 'PROPOSED') AS PROPOSED_STORES
FROM RAW_COFFEE_SHOP_LOCATIONS;

-- Spot-check spatial values as WKT.
SELECT DEVICE_ID, LATITUDE, LONGITUDE, ST_ASWKT(LOCATION_GEOG) AS LOCATION_WKT
FROM RAW_GPS_PINGS LIMIT 10;

SELECT COFFEE_SHOP_ID, COFFEE_SHOP_NAME, AREA, LOCATION_TYPE,
       ST_ASWKT(LOCATION_GEOG) AS LOCATION_WKT
FROM RAW_COFFEE_SHOP_LOCATIONS ORDER BY COFFEE_SHOP_ID;

-- Invalid/missing coordinate checks.
SELECT 'GPS_PINGS' AS DATASET, COUNT(*) AS INVALID_COORDINATE_ROWS
FROM RAW_GPS_PINGS
WHERE LATITUDE IS NULL OR LONGITUDE IS NULL
   OR LATITUDE NOT BETWEEN -90 AND 90
   OR LONGITUDE NOT BETWEEN -180 AND 180
UNION ALL
SELECT 'COFFEE_SHOPS', COUNT(*)
FROM RAW_COFFEE_SHOP_LOCATIONS
WHERE LATITUDE IS NULL OR LONGITUDE IS NULL
   OR LATITUDE NOT BETWEEN -90 AND 90
   OR LONGITUDE NOT BETWEEN -180 AND 180;
